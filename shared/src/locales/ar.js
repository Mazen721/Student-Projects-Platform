function resolvePath(obj, dotPath) {
  if (!dotPath || typeof dotPath !== 'string') return undefined;
  return dotPath.split('.').reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj);
}

export function t(key, vars = {}) {
  const raw = resolvePath(ar, key);
  if (typeof raw !== 'string') {
    return key;
  }
  return raw.replace(/\{(\w+)\}/g, (match, token) => (
    Object.prototype.hasOwnProperty.call(vars, token) ? String(vars[token]) : match
  ));
}

const arabicPluralRules = new Intl.PluralRules('ar-EG');

export function pluralAr(count, forms) {
  const category = arabicPluralRules.select(count);
  const template = forms[category] ?? forms.other ?? '';
  return template.replace(/\{count\}/g, String(count));
}

